// Package auth handles YouTube Music credentials.
//
// Authentication works by extracting your existing browser session cookies
// (specifically SAPISID, which the client turns into a SAPISIDHASH header) —
// the same technique ytmusicapi and yt-dlp use. Cookies can be read
// automatically from an installed browser via kooky, or pasted manually.
package auth

import (
	"bufio"
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/browserutils/kooky"
	_ "github.com/browserutils/kooky/browser/all" // register all cookie store finders
)

const appName = "ytmusic-tui"

// Dir returns the app's config directory (~/.config/ytmusic-tui).
func Dir() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return "."
	}
	return filepath.Join(home, ".config", appName)
}

// AuthFilePath returns the path to the saved auth file.
func AuthFilePath() string { return filepath.Join(Dir(), "auth.json") }

type fileAuth struct {
	Cookie  string `json:"cookie"`
	Browser string `json:"browser,omitempty"`
	Profile string `json:"profile,omitempty"`
	SavedAt string `json:"savedAt,omitempty"`
	// Compatibility with ytmusicapi-style files that use a capitalised key.
	CookieUpper string `json:"Cookie,omitempty"`
}

// IsConfigured reports whether an auth file with a usable cookie exists.
func IsConfigured() bool {
	c, err := Cookie()
	return err == nil && c != ""
}

// Cookie reads the saved Cookie header, or an error if none is present.
func Cookie() (string, error) {
	data, err := os.ReadFile(AuthFilePath())
	if err != nil {
		return "", err
	}
	var fa fileAuth
	if err := json.Unmarshal(data, &fa); err != nil {
		return "", fmt.Errorf("auth file is not valid JSON: %w", err)
	}
	cookie := strings.TrimSpace(fa.Cookie)
	if cookie == "" {
		cookie = strings.TrimSpace(fa.CookieUpper)
	}
	if cookie == "" {
		return "", fmt.Errorf("auth file has no cookie — re-run `ytm auth`")
	}
	return cookie, nil
}

// SaveCookie persists the Cookie header to auth.json with 0600 permissions.
// profile records which browser profile the cookie came from (may be empty).
func SaveCookie(cookie, browser, profile string) error {
	cookie = sanitizeCookie(cookie)
	if cookie == "" {
		return fmt.Errorf("refusing to save an empty cookie")
	}
	if err := os.MkdirAll(Dir(), 0o700); err != nil {
		return err
	}
	fa := fileAuth{
		Cookie:  cookie,
		Browser: browser,
		Profile: profile,
		SavedAt: time.Now().Format(time.RFC3339),
	}
	data, err := json.MarshalIndent(fa, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(AuthFilePath(), data, 0o600)
}

// WriteNetscapeCookies writes the stored cookie as a Netscape-format cookie
// file (0600) for tools like yt-dlp that accept --cookies. The account cookies
// apply to .youtube.com, so they are all written under that domain.
func WriteNetscapeCookies(path string) error {
	cookie, err := Cookie()
	if err != nil {
		return err
	}

	f, err := os.OpenFile(path, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0o600)
	if err != nil {
		return err
	}
	defer f.Close()

	w := bufio.NewWriter(f)
	fmt.Fprintln(w, "# Netscape HTTP Cookie File")
	fmt.Fprintln(w, "# Generated by ytm on each launch; do not edit.")
	expiry := time.Now().AddDate(1, 0, 0).Unix()
	for _, part := range strings.Split(cookie, ";") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		name, value, ok := strings.Cut(part, "=")
		name = strings.TrimSpace(name)
		if !ok || name == "" {
			continue
		}
		// domain  includeSubdomains  path  secure  expiry  name  value
		fmt.Fprintf(w, ".youtube.com\tTRUE\t/\tTRUE\t%d\t%s\t%s\n", expiry, name, value)
	}
	return w.Flush()
}

// Resolve returns a usable cookie, preferring a live browser session so the
// session never goes stale, and falling back to the saved auth file. The
// source string is "browser:<name>" or "auth.json".
func Resolve() (cookie, source string, err error) { return ResolveWith("", "") }

// ResolveWith is Resolve constrained to a specific browser (and optionally a
// profile within it). Empty browser/profile mean auto-detect. When a browser is
// named but yields nothing, it still falls back to the saved auth file.
func ResolveWith(browser, profile string) (cookie, source string, err error) {
	if c, b, ferr := FromBrowserProfile(browser, profile); ferr == nil && c != "" {
		return c, "browser:" + b, nil
	}
	if c, cerr := Cookie(); cerr == nil && c != "" {
		return c, "auth.json", nil
	}
	return "", "", fmt.Errorf("no credentials found; run `ytm auth`")
}

// RunSetup obtains a cookie and saves it. If paste is true (or automatic
// extraction fails) it prompts the user to paste the Cookie header manually.
// browser/profile optionally restrict automatic extraction.
func RunSetup(browser, profile string, paste bool) error {
	if !paste {
		cookie, usedBrowser, err := FromBrowserProfile(browser, profile)
		if err == nil {
			if err := SaveCookie(cookie, usedBrowser, profile); err != nil {
				return err
			}
			fmt.Printf("Authenticated using %s cookies.\n", usedBrowser)
			return nil
		}
		fmt.Fprintf(os.Stderr, "Automatic cookie extraction failed: %v\n\n", err)
		fmt.Println("Falling back to manual paste.")
		PrintSetupInstructions()
	}
	cookie, err := promptCookie()
	if err != nil {
		return err
	}
	if err := SaveCookie(cookie, "manual", ""); err != nil {
		return err
	}
	fmt.Println("Authenticated. Saved to " + AuthFilePath())
	return nil
}

// groupKey identifies one browser profile's cookie set.
type groupKey struct{ browser, profile string }

// Profile is a browser profile that holds YouTube login cookies.
type Profile struct {
	Browser string
	Profile string
}

// Label renders the profile for display, e.g. "firefox · Default (release)".
func (p Profile) Label() string {
	if p.Profile == "" {
		return p.Browser
	}
	return p.Browser + " · " + p.Profile
}

// FromBrowser extracts YouTube/Google cookies from an installed browser and
// returns a Cookie header. If browser is non-empty only that browser is used.
func FromBrowser(browser string) (cookie string, usedBrowser string, err error) {
	return FromBrowserProfile(browser, "")
}

// FromBrowserProfile is FromBrowser constrained to a specific browser profile.
// An empty profile matches any profile within the browser.
func FromBrowserProfile(browser, profile string) (cookie string, usedBrowser string, err error) {
	groups, order := collectCookieGroups(browser)

	for _, k := range order {
		g := groups[k]
		if g["SAPISID"] == "" {
			continue
		}
		if browser != "" && !strings.EqualFold(browser, k.browser) {
			continue
		}
		if profile != "" && !matchProfile(profile, k.profile) {
			continue
		}
		return buildCookieHeader(g), k.browser, nil
	}
	if browser != "" {
		if profile != "" {
			return "", "", fmt.Errorf("no YouTube login cookies found in %s profile %q (are you signed in there?)", browser, profile)
		}
		return "", "", fmt.Errorf("no YouTube login cookies found in %s (are you signed in there?)", browser)
	}
	return "", "", fmt.Errorf("no signed-in browser with YouTube cookies found")
}

// ListProfiles returns every browser profile that holds YouTube login cookies,
// ordered by discovery. It is what `ytm profiles` prints and what the picker
// offers.
func ListProfiles() []Profile {
	groups, order := collectCookieGroups("")
	var out []Profile
	for _, k := range order {
		if groups[k]["SAPISID"] == "" {
			continue
		}
		out = append(out, Profile{Browser: k.browser, Profile: k.profile})
	}
	return out
}

// collectCookieGroups traverses installed browsers (optionally restricted to
// one browser name) and groups YouTube/Google cookies by browser profile.
func collectCookieGroups(browser string) (map[groupKey]map[string]string, []groupKey) {
	ctx := context.Background()
	groups := map[groupKey]map[string]string{}
	var order []groupKey

	add := func(k groupKey, c *kooky.Cookie) {
		dom := strings.TrimPrefix(c.Domain, ".")
		if !strings.HasSuffix(dom, "youtube.com") && !strings.HasSuffix(dom, "google.com") {
			return
		}
		if groups[k] == nil {
			groups[k] = map[string]string{}
			order = append(order, k)
		}
		groups[k][c.Name] = c.Value
	}

	for c, cErr := range kooky.TraverseCookies(ctx, kooky.Valid) {
		if cErr != nil || c == nil {
			continue
		}
		b, profile := "", ""
		if c.Browser != nil {
			b = c.Browser.Browser()
			profile = c.Browser.Profile()
		}
		if browser != "" && !strings.EqualFold(b, browser) {
			continue
		}
		add(groupKey{b, profile}, c)
	}
	return groups, order
}

// matchProfile reports whether a stored/known profile name satisfies a
// requested one. Matching is case-insensitive and ignores surrounding
// whitespace; a request may also name just the final path element (so
// "Default (release)" matches "some/root/Default (release)").
func matchProfile(want, got string) bool {
	want = strings.TrimSpace(want)
	got = strings.TrimSpace(got)
	if want == "" || got == "" {
		return want == got
	}
	if strings.EqualFold(want, got) {
		return true
	}
	return strings.EqualFold(want, filepath.Base(got))
}

// ParseProfileRef parses a "browser" or "browser/profile" reference (as accepted
// on the command line) into its parts. Whitespace is trimmed and a lone slash
// yields an empty profile.
func ParseProfileRef(s string) (browser, profile string) {
	s = strings.TrimSpace(s)
	if s == "" {
		return "", ""
	}
	if b, p, ok := strings.Cut(s, "/"); ok {
		return strings.TrimSpace(b), strings.TrimSpace(p)
	}
	return s, ""
}

// buildCookieHeader renders a cookie map as a "name=value; ..." header.
func buildCookieHeader(m map[string]string) string {
	names := make([]string, 0, len(m))
	for n := range m {
		names = append(names, n)
	}
	sort.Strings(names)
	parts := make([]string, 0, len(names))
	for _, n := range names {
		parts = append(parts, n+"="+m[n])
	}
	return strings.Join(parts, "; ")
}

func promptCookie() (string, error) {
	fmt.Println("Paste the value of the `Cookie:` request header from music.youtube.com")
	fmt.Println("(DevTools → Network → any request → Request Headers → Cookie), then press Enter:")
	reader := bufio.NewReader(os.Stdin)
	line, err := reader.ReadString('\n')
	if err != nil && line == "" {
		return "", err
	}
	return sanitizeCookie(line), nil
}

// sanitizeCookie trims prefixes/whitespace users commonly include when pasting.
func sanitizeCookie(s string) string {
	s = strings.TrimSpace(s)
	s = strings.TrimPrefix(s, "Cookie:")
	s = strings.TrimPrefix(s, "cookie:")
	s = strings.TrimSpace(s)
	s = strings.Trim(s, `"'`)
	return strings.TrimSpace(s)
}

// PrintSetupInstructions explains how to authenticate.
func PrintSetupInstructions() {
	fmt.Print(`
To sign in, either:
  1. Run ` + "`ytm auth`" + ` with a signed-in Firefox/Chrome/Brave/Edge installed —
     cookies are read automatically, or
  2. Run ` + "`ytm auth --paste`" + ` and paste the Cookie header from a music.youtube.com
     request (DevTools → Network → Request Headers → Cookie).

To force one browser: ` + "`ytm auth --browser firefox`" + `.

Saved to ` + AuthFilePath() + ` (chmod 600). It stays valid for months; re-run
only if you sign out or change your Google password.
`)
}

// WaitForEnter pauses until the user presses Enter.
func WaitForEnter() {
	fmt.Print("Press Enter to continue...")
	bufio.NewReader(os.Stdin).ReadString('\n')
}
